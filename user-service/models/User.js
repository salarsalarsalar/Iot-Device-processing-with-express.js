const { mongoose } = require('mongoose');

const UserSchema = mongoose.Schema({
    username: {
        type: String,
        required: true,
        unique: true
    },
    email: {
        type: String,
        required: true,
        unique: true
    },
    password: {
        type: String,
        required: true
    }
}, {
    timestamps: false,
    collection: 'users'
});
const User = mongoose.model('User', UserSchema);
module.exports = User; 